package star.tracto.preprocessing;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static star.tracto.preprocessing.TokensFixture.candidatesAfter;

/**
 * End-to-end test of the class names offered as candidate tokens (Step 26): the classes visible in the test class by
 * their simple name, following the rules of Java: the classes of {@code java.lang}, the classes imported (one by one,
 * nested classes included, or with a wildcard), the classes of the package of the test class (not of its subpackages,
 * interfaces included), the classes declared in the test class. The classes generated by the pipeline (the split test
 * class, the normalized one, the prefix class) are not offered.
 */
class ClassNamesTokensTest {

    @TempDir
    Path tempDir;

    private TokensFixture fixture;

    @BeforeEach
    void setUp() throws IOException {
        fixture = new TokensFixture(tempDir);
        fixture.write("src/main/java/com/acme/Clock.java", """
                package com.acme;

                public class Clock implements Shape {
                    public long now() {
                        return 1L;
                    }
                }
                """);
        fixture.write("src/main/java/com/acme/Shape.java", """
                package com.acme;

                public interface Shape {
                    int SIDES = 4;
                }
                """);
        fixture.write("src/main/java/com/acme/util/Hidden.java", """
                package com.acme.util;

                public class Hidden {
                    public static int value() {
                        return 1;
                    }
                }
                """);
        fixture.write("src/main/java/com/acme/doc/Document.java", """
                package com.acme.doc;

                public class Document {
                    public static class Settings {
                        public enum Syntax { html, xml }

                        public static int indent() {
                            return 2;
                        }
                    }
                }
                """);
        fixture.write("src/main/java/com/acme/event/Event.java", """
                package com.acme.event;

                public record Event(String name) {
                }
                """);
        fixture.write("src/main/java/com/acme/doc/Node.java", """
                package com.acme.doc;

                public class Node {
                    public static int count() {
                        return 0;
                    }
                }
                """);
        fixture.write("src/test/java/com/acme/ClockTest.java", """
                package com.acme;

                import java.util.List;
                import org.junit.jupiter.api.Test;
                import com.acme.doc.Document;
                import com.acme.doc.Document.Settings;
                import com.acme.doc.*;
                import com.acme.event.Event;
                import static org.junit.jupiter.api.Assertions.*;

                public class ClockTest {

                    static class Helper {
                        static int one() {
                            return 1;
                        }
                    }

                    @Test
                    public void testJavaLangException() {
                        Clock clock = new Clock();
                        assertThrows(IllegalArgumentException.class, () -> clock.now());
                    }

                    @Test
                    public void testJavaLangStaticMethod() {
                        assertEquals("1", String.valueOf(1));
                    }

                    @Test
                    public void testImportedNestedClass() {
                        assertEquals(2, Settings.indent());
                    }

                    @Test
                    public void testQualifiedNestedClass() {
                        assertEquals(Document.Settings.Syntax.xml, Document.Settings.Syntax.valueOf("xml"));
                    }

                    @Test
                    public void testWildcardImport() {
                        assertEquals(0, Node.count());
                    }

                    @Test
                    public void testJdkImport() {
                        assertEquals(List.of(), List.of());
                    }

                    @Test
                    public void testSamePackageInterface() {
                        Clock clock = new Clock();
                        assertTrue(clock instanceof Shape);
                    }

                    @Test
                    public void testNestedClassOfTheTestClass() {
                        assertEquals(1, Helper.one());
                    }
                }
                """);
    }

    @Test
    void theClassesVisibleInTheTestClassAreOffered() throws IOException {
        fixture.generate();

        assertEquals(Map.of(), fixture.unexpectedTokens());
        assertEquals(List.of("testImportedNestedClass_split_0", "testJavaLangException_split_0",
                "testJavaLangStaticMethod_split_0", "testJdkImport_split_0", "testNestedClassOfTheTestClass_split_0",
                "testQualifiedNestedClass_split_0", "testSamePackageInterface_split_0", "testWildcardImport_split_0"),
                fixture.tokensDatapoints().keySet().stream().sorted().toList());
    }

    @Test
    void onlyTheClassesVisibleByTheirSimpleNameAreOffered() throws IOException {
        fixture.generate();

        List<String> candidates = candidatesAfter(fixture.tokensDatapoints().get("testJavaLangStaticMethod_split_0"), "assertEquals(\"1\",");
        for (String name : List.of("String", "Math", "IllegalArgumentException", "List", "Document", "Settings", "Node", "Event",
                "Clock", "Shape", "Helper", "ClockTest")) {
            assertTrue(candidates.contains(name), name + " " + candidates);
        }
        // A class of a subpackage, of a package of java.lang (java.lang.reflect), a nested class not imported
        for (String name : List.of("Hidden", "Method", "Syntax")) {
            assertFalse(candidates.contains(name), name + " " + candidates);
        }
        // The classes generated by the pipeline
        for (String name : List.of("ClockTestSTARSplitTest", "ClockTestSTARNormalizedTest", "ClockTestSTARSplitTestPrefix")) {
            assertFalse(candidates.contains(name), name + " " + candidates);
        }
        // After `instanceof`: the classes visible in the test class (not the context of the expression tested)
        candidates = candidatesAfter(fixture.tokensDatapoints().get("testSamePackageInterface_split_0"), "assertTrue(clock instanceof ");
        assertTrue(candidates.contains("Shape"), candidates.toString());
        assertTrue(candidates.contains("Clock"), candidates.toString());
    }

    @Test
    void theNestedClassesOfAClassAreOfferedAfterItsName() throws IOException {
        fixture.generate();

        List<String> candidates = candidatesAfter(fixture.tokensDatapoints().get("testQualifiedNestedClass_split_0"), "assertEquals(Document.Settings.");
        assertTrue(candidates.contains("Syntax"), candidates.toString());
        candidates = candidatesAfter(fixture.tokensDatapoints().get("testQualifiedNestedClass_split_0"), "assertEquals(Document.Settings.Syntax.");
        assertTrue(candidates.contains("xml"), candidates.toString());
    }
}
