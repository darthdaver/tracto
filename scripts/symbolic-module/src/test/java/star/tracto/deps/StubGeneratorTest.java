package star.tracto.deps;

import com.github.javaparser.ParseResult;
import com.github.javaparser.JavaParser;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.ast.CompilationUnit;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import javax.tools.ToolProvider;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.*;

/**
 * The stubs of compiled classes (Step 38): what the symbol solver and the candidates need (the classes, their generic
 * signatures, their accessible members, the names of the parameters), in Java that JavaParser parses.
 */
class StubGeneratorTest {

    @TempDir
    Path tempDir;

    private static final String SOURCE = """
            package org.lib;

            import java.util.List;
            import java.util.Map;

            public class Box<T extends Comparable<T>> implements Iterable<T> {
                public static final int SIZE = 4;
                public List<? extends T> items;
                protected Map.Entry<String, T> entry;
                int local;
                private String hidden;
                public static Class class$0;

                public Box(List<? extends T> items) {
                    this.items = items;
                }

                private Box() {
                }

                public <R> R map(java.util.function.Function<? super T, R> mapper, long times, String... labels) throws java.io.IOException {
                    return null;
                }

                public static Box<String> of(String value) {
                    return null;
                }

                private int secret() {
                    return 1;
                }

                public java.util.Iterator<T> iterator() {
                    return null;
                }

                public static class Nested {
                    public double depth() {
                        return 1;
                    }
                }

                public class Inner {
                    public Inner(int level) {
                    }
                }

                public enum Kind {
                    SMALL, LARGE;

                    public boolean big() {
                        return this == LARGE;
                    }
                }

                public interface Shape {
                    int SIDES = 3;

                    int area();

                    default int twice() {
                        return 2 * area();
                    }

                    static Shape unit() {
                        return null;
                    }
                }

                public @interface Tag {
                    String value();
                }

                private static class Hidden {
                }

                public Runnable task() {
                    return new Runnable() {
                        public void run() {
                        }
                    };
                }
            }
            """;

    @Test
    void theStubKeepsWhatTheSolverNeeds() throws IOException {
        Map<String, String> stubs = StubGenerator.stubs("lib-1.0.jar", compile("org/lib/Box.java", SOURCE));

        // One file per top-level class: the nested, anonymous and private classes are not top level
        assertEquals(List.of("org.lib.Box"), List.copyOf(stubs.keySet()));
        String stub = stubs.get("org.lib.Box");
        assertTrue(stub.startsWith(StubGenerator.MARKER + " lib-1.0.jar\npackage org.lib;"), stub);
        assertTrue(stub.contains("public class Box<T extends java.lang.Comparable<T>> implements java.lang.Iterable<T> {"), stub);
        // Fields: generic types, nested types with dots; not the private ones
        assertTrue(stub.contains("public static final int SIZE;"), stub);
        assertTrue(stub.contains("public java.util.List<? extends T> items;"), stub);
        assertTrue(stub.contains("protected java.util.Map.Entry<java.lang.String, T> entry;"), stub);
        assertTrue(stub.contains("    int local;"), stub);
        assertFalse(stub.contains("hidden"), stub);
        // A name with a $: generated by a compiler
        assertFalse(stub.contains("class$0"), stub);
        // Methods and constructors: type parameters, parameter names, varargs, throws; not the private ones
        assertTrue(stub.contains("public Box(java.util.List<? extends T> items) {}"), stub);
        assertFalse(stub.contains("Box() {}"), stub);
        assertTrue(stub.contains("public <R> R map(java.util.function.Function<? super T, R> mapper, long times, java.lang.String... labels) throws java.io.IOException {}"), stub);
        assertTrue(stub.contains("public static org.lib.Box<java.lang.String> of(java.lang.String value) {}"), stub);
        assertFalse(stub.contains("secret"), stub);
        // Member classes: static, inner (without the outer instance in the constructor), enum, interface, annotation
        assertTrue(stub.contains("public static class Nested {"), stub);
        assertTrue(stub.contains("public double depth() {}"), stub);
        assertTrue(stub.contains("public class Inner {"), stub);
        assertTrue(stub.contains("public Inner(int level) {}"), stub);
        assertTrue(stub.contains("public enum Kind {"), stub);
        assertTrue(stub.contains("SMALL, LARGE;"), stub);
        assertTrue(stub.contains("public boolean big() {}"), stub);
        assertFalse(stub.contains("values()"), stub);
        assertFalse(stub.contains("valueOf("), stub);
        assertTrue(stub.contains("public interface Shape {"), stub);
        assertTrue(stub.contains("int SIDES;"), stub);
        assertTrue(stub.contains("int area();"), stub);
        assertTrue(stub.contains("default int twice() {}"), stub);
        assertTrue(stub.contains("static org.lib.Box.Shape unit() {}"), stub);
        assertTrue(stub.contains("public @interface Tag {"), stub);
        assertTrue(stub.contains("java.lang.String value();"), stub);
        assertFalse(stub.contains("Hidden"), stub);
        // Java that JavaParser parses
        ParseResult<CompilationUnit> parsed = new JavaParser(new ParserConfiguration()
                .setLanguageLevel(ParserConfiguration.LanguageLevel.JAVA_21)).parse(stub);
        assertTrue(parsed.isSuccessful(), parsed.getProblems() + "\n" + stub);
    }

    @Test
    void theSameJarGivesTheSameStubs() throws IOException {
        List<byte[]> classes = compile("org/lib/Box.java", SOURCE);
        assertEquals(StubGenerator.stubs("a.jar", classes), StubGenerator.stubs("a.jar", classes));
    }

    /** Compiles a source file with the debug information (as Maven does by default) and returns its class files. */
    private List<byte[]> compile(String relativePath, String source) throws IOException {
        Path sourceFile = tempDir.resolve("src").resolve(relativePath);
        Files.createDirectories(sourceFile.getParent());
        Files.writeString(sourceFile, source);
        Path classes = tempDir.resolve("classes");
        Files.createDirectories(classes);
        assertEquals(0, ToolProvider.getSystemJavaCompiler().run(null, null, null, "-g", "-d", classes.toString(), sourceFile.toString()));
        List<byte[]> result = new ArrayList<>();
        try (Stream<Path> files = Files.walk(classes)) {
            for (Path file : files.filter(f -> f.toString().endsWith(".class")).sorted().toList()) {
                result.add(Files.readAllBytes(file));
            }
        }
        return result;
    }
}
