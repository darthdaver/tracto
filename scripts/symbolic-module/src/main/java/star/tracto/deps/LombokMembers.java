package star.tracto.deps;

import com.github.javaparser.JavaParser;
import com.github.javaparser.ParseResult;
import com.github.javaparser.ParserConfiguration;
import com.github.javaparser.Position;
import com.github.javaparser.ast.CompilationUnit;
import com.github.javaparser.ast.Node;
import com.github.javaparser.ast.body.BodyDeclaration;
import com.github.javaparser.ast.body.EnumDeclaration;
import com.github.javaparser.ast.body.TypeDeclaration;
import com.github.javaparser.ast.nodeTypes.NodeWithAnnotations;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Stream;

/**
 * The members generated by Lombok added to the sources of a project (Step 43). Delombok reprints the whole file: it
 * also rewrites the code written by the developer (the initializers of {@code @Builder.Default} fields, {@code val},
 * the bodies of {@code @SneakyThrows} methods, the place of some comments). The copies read by the symbol solver are
 * therefore the original files, unchanged, with the members delombok marks {@code @lombok.Generated} (getters,
 * setters, constructors, builders, the logger of {@code @Slf4j}) inserted as text before the closing brace of their
 * type: the members and the code seen by the model are the ones of the sources, plus the generated ones.
 *
 * <p>Usage: {@code lombok-members <source root> <delomboked root>}: each file of the delomboked root is replaced by
 * the merge of its original (same relative path in the source root) and of the generated members. A file that cannot
 * be merged (a file that does not parse, a type without its original) keeps the output of delombok.</p>
 */
public final class LombokMembers {

    private static final String GENERATED = "lombok.Generated";

    private LombokMembers() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            System.err.println("Usage: lombok-members <source root> <delomboked root>");
            System.exit(2);
        }
        int[] counts = mergeAll(Path.of(args[0]), Path.of(args[1]));
        System.out.println("Lombok members: " + counts[0] + " files merged, " + counts[1] + " kept as delomboked");
    }

    /** Merges every file of the delomboked root with its original; returns the files merged and the files kept. */
    static int[] mergeAll(Path sourceRoot, Path delombokedRoot) throws IOException {
        int merged = 0;
        int kept = 0;
        List<Path> copies;
        try (Stream<Path> files = Files.walk(delombokedRoot)) {
            copies = files.filter(path -> path.toString().endsWith(".java") && Files.isRegularFile(path)).sorted().toList();
        }
        for (Path copy : copies) {
            Path original = sourceRoot.resolve(delombokedRoot.relativize(copy).toString());
            Optional<String> result = Files.isRegularFile(original)
                    ? merge(Files.readString(original, StandardCharsets.UTF_8), Files.readString(copy, StandardCharsets.UTF_8))
                    : Optional.empty();
            if (result.isPresent()) {
                Files.writeString(copy, result.get(), StandardCharsets.UTF_8);
                merged++;
            } else {
                System.err.println("Lombok members: " + copy + " kept as delomboked");
                kept++;
            }
        }
        return new int[]{merged, kept};
    }

    /**
     * The original source with the members generated by Lombok of the delomboked one, or empty if they cannot be
     * merged.
     */
    static Optional<String> merge(String original, String delomboked) {
        Optional<CompilationUnit> originalCu = parse(original);
        Optional<CompilationUnit> delombokedCu = parse(delomboked);
        if (originalCu.isEmpty() || delombokedCu.isEmpty()) {
            return Optional.empty();
        }
        Map<String, TypeDeclaration<?>> originalTypes = types(originalCu.get());
        // The insertions: the position of the closing brace of a type of the original, the text inserted before it
        List<Map.Entry<Position, String>> insertions = new ArrayList<>();
        for (Map.Entry<String, TypeDeclaration<?>> entry : types(delombokedCu.get()).entrySet()) {
            TypeDeclaration<?> copy = entry.getValue();
            List<BodyDeclaration<?>> generated = copy.getMembers().stream().filter(LombokMembers::isGenerated).toList();
            if (generated.isEmpty()) {
                continue;
            }
            TypeDeclaration<?> target = originalTypes.get(entry.getKey());
            if (target == null || target.getEnd().isEmpty()) {
                return Optional.empty();
            }
            StringBuilder text = new StringBuilder();
            if (target instanceof EnumDeclaration enumDeclaration && !hasMemberSeparator(original, enumDeclaration)) {
                // The constants of an enum without members end with a semicolon before the first member
                text.append(";");
            }
            for (BodyDeclaration<?> member : generated) {
                Optional<String> memberText = textOf(delomboked, member);
                if (memberText.isEmpty()) {
                    return Optional.empty();
                }
                text.append("\n").append(memberText.get()).append("\n");
            }
            insertions.add(Map.entry(target.getEnd().get(), text.toString()));
        }
        if (insertions.isEmpty()) {
            return Optional.of(original);
        }
        // From the last position to the first, so that the earlier offsets stay valid
        insertions.sort(Comparator.comparing((Map.Entry<Position, String> insertion) -> insertion.getKey()).reversed());
        int[] lineStarts = lineStarts(original);
        StringBuilder merged = new StringBuilder(original);
        for (Map.Entry<Position, String> insertion : insertions) {
            merged.insert(offset(lineStarts, insertion.getKey()), insertion.getValue());
        }
        String result = merged.toString();
        return parse(result).map(cu -> result);
    }

    private static boolean isGenerated(BodyDeclaration<?> member) {
        return member instanceof NodeWithAnnotations<?> annotated
                && annotated.getAnnotations().stream().anyMatch(annotation -> annotation.getNameAsString().equals(GENERATED));
    }

    /** The types of a compilation unit, by their path of names ({@code Outer.Inner}), not the generated ones. */
    private static Map<String, TypeDeclaration<?>> types(CompilationUnit cu) {
        Map<String, TypeDeclaration<?>> types = new LinkedHashMap<>();
        for (TypeDeclaration<?> type : cu.getTypes()) {
            addTypes(type, type.getNameAsString(), types);
        }
        return types;
    }

    private static void addTypes(TypeDeclaration<?> type, String path, Map<String, TypeDeclaration<?>> types) {
        types.put(path, type);
        for (BodyDeclaration<?> member : type.getMembers()) {
            if (member instanceof TypeDeclaration<?> memberType && !isGenerated(memberType)) {
                addTypes(memberType, path + "." + memberType.getNameAsString(), types);
            }
        }
    }

    /** Whether the constants of an enum are followed by a semicolon (always when it has members). */
    private static boolean hasMemberSeparator(String source, EnumDeclaration enumDeclaration) {
        if (!enumDeclaration.getMembers().isEmpty()) {
            return true;
        }
        Optional<Position> end = enumDeclaration.getEnd();
        Optional<Position> afterConstants = enumDeclaration.getEntries().isEmpty()
                ? enumDeclaration.getName().getEnd()
                : enumDeclaration.getEntries().getLast().flatMap(Node::getEnd);
        if (end.isEmpty() || afterConstants.isEmpty()) {
            return false;
        }
        int[] lineStarts = lineStarts(source);
        return source.substring(offset(lineStarts, afterConstants.get()) + 1, offset(lineStarts, end.get())).contains(";");
    }

    /** The text of a member in its source, with its Javadoc or comment. */
    private static Optional<String> textOf(String source, BodyDeclaration<?> member) {
        Optional<Position> begin = member.getComment().flatMap(Node::getBegin).or(member::getBegin);
        Optional<Position> end = member.getEnd();
        if (begin.isEmpty() || end.isEmpty()) {
            return Optional.empty();
        }
        int[] lineStarts = lineStarts(source);
        return Optional.of(source.substring(offset(lineStarts, begin.get()), offset(lineStarts, end.get()) + 1));
    }

    private static int[] lineStarts(String source) {
        List<Integer> starts = new ArrayList<>();
        starts.add(0);
        for (int i = 0; i < source.length(); i++) {
            if (source.charAt(i) == '\n') {
                starts.add(i + 1);
            }
        }
        return starts.stream().mapToInt(Integer::intValue).toArray();
    }

    /** The offset of a position (line and column from 1, a tab counting as one column, as JavaParser counts them). */
    private static int offset(int[] lineStarts, Position position) {
        return lineStarts[position.line - 1] + position.column - 1;
    }

    private static Optional<CompilationUnit> parse(String source) {
        ParseResult<CompilationUnit> result = new JavaParser(new ParserConfiguration()
                .setLanguageLevel(ParserConfiguration.LanguageLevel.BLEEDING_EDGE)).parse(source);
        return result.isSuccessful() ? result.getResult() : Optional.empty();
    }
}
