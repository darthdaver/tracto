package star.tracto;

import com.fasterxml.jackson.databind.ObjectMapper;
import star.tracto.data.enums.NamingConvention;
import star.tracto.deps.StubGenerator;
import star.tracto.deps.LombokMembers;
import star.tracto.preprocessing.OraclesDataset;
import star.tracto.preprocessing.TokensDataset;
import star.tracto.utils.JavaUtils;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.Optional;

public class SymbolicModule {

    public static void main(String[] args) {
        // Process arguments
        String datasetType = args[0];
        // Project identifier
        try {
            if (datasetType.equals("inference") || datasetType.equals("test")) {
                Client.run(args);
            } else if (datasetType.equals("stubs")) {
                // The stubs of a jar without sources (Step 38): stubs <jar> <output folder>
                StubGenerator.main(Arrays.copyOfRange(args, 1, args.length));
            } else if (datasetType.equals("lombok-members")) {
                // The members generated by Lombok added to the sources (Step 43): lombok-members <source root> <delomboked root>
                LombokMembers.main(Arrays.copyOfRange(args, 1, args.length));
            } else {
                String projectIdentifier = args[1];
                Path repoRootPath = Path.of(args[2]);
                Path outputPath = Path.of(args[3]);
                Path basePath = Path.of(args[4]);
                // The Java version of the repository: a major version, or `auto` to detect it from its build files
                JavaUtils.setJavaLibPath(basePath, args[5], repoRootPath);
                String classpath = JavaUtils.initializeJavaClassPath();
                if (datasetType.equals("oracles")) {
                    Path configPath = Path.of(args[6]);
                    Optional<Path> repoTrackPath = args.length > 7 ? Optional.of(Path.of(args[7])) : Optional.empty();
                    OraclesDataset.generate(repoRootPath, repoTrackPath, configPath, outputPath, projectIdentifier, classpath);
                } else if (datasetType.equals("tokens")) {
                    String mode = args.length > 6 ? args[6] : "training";
                    TokensDataset.generate(repoRootPath, outputPath, mode, projectIdentifier, classpath);
                }
            }
        } catch (IOException e) {
            e.printStackTrace();
        }
    }

    public static List<Path> findLibrariesPaths(Path repoRootPath) {
        List<Path> matchingPaths = new ArrayList<>();
        try {
            Files.walkFileTree(repoRootPath, new SimpleFileVisitor<>() {
                @Override
                public FileVisitResult preVisitDirectory(Path dir, BasicFileAttributes attrs) throws IOException {
                    // The sources of the libraries (one folder each) and the binary jars of the libraries without
                    // sources (tools/deps/resolve_maven.py, Step 38)
                    if (dir.toString().endsWith(NamingConvention.DECOMPILED_LIB_FOLDER.getConventionName())
                            || dir.toString().endsWith(NamingConvention.JAR_LIB_FOLDER.getConventionName())) {
                        matchingPaths.add(dir);
                    }
                    return FileVisitResult.CONTINUE;
                }
            });
        } catch (IOException e) {
            System.err.println("Error while searching for folders: " + e.getMessage());
        }
        // In a fixed order (Step 38): the order of the libraries given to the symbol solver
        matchingPaths.sort(null);
        return matchingPaths;
    }
}
